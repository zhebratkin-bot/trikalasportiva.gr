// Helper functions for data retrieval
const sportsNewsStore = {
  getAll: () => [...sportsNewsData].sort((a, b) => new Date(b.dateIso) - new Date(a.dateIso)),
  
  getHeroArticles: () => {
    // Returns 4 articles for the hero grid (latest ones)
    const sorted = sportsNewsStore.getAll();
    return sorted.slice(0, 4);
  },
  
  getByCategory: (category) => {
    return sportsNewsData
      .filter(item => item.category === category)
      .sort((a, b) => new Date(b.dateIso) - new Date(a.dateIso));
  },
  
  getById: (id) => {
    return sportsNewsData.find(item => item.id === parseInt(id));
  },
  
  getRelated: (id, category, limit = 3) => {
    return sportsNewsData
      .filter(item => item.category === category && item.id !== parseInt(id))
      .slice(0, limit);
  },

  getLatestNewsExceptHero: (limit = 6) => {
    const sorted = sportsNewsStore.getAll();
    return sorted.slice(4, 4 + limit);
  },

  getAuthorById: (id) => sportsAuthors.find(a => a.id === parseInt(id)),

  getAuthorBySlug: (slug) => sportsAuthors.find(a => a.slug === slug),

  getByAuthor: (authorId) => sportsNewsData
    .filter(item => item.authorId === parseInt(authorId))
    .sort((a, b) => new Date(b.dateIso) - new Date(a.dateIso))
};
